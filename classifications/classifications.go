// Classify returns the Classification for the given error code, or Unknown
// if the code is not in the catalog. It never returns an error, and is safe
// for concurrent use as long as nothing writes to Classifications directly.
func Classify(code string) Classification {
	if c, ok := Classifications[code]; ok {
		return c
	}
	return Unknown
}
