// Package classifications maps every Snyk error code to its Classification.
// Classify never returns an error: an unrecognised code resolves to Unknown.
//
// Example:
//
//	c := classifications.Classify(errorCode)
//	if c == classifications.Unexpected { /* alert */ }
package classifications

// Classification is the category of a Snyk error code. See the ErrorCatalog
